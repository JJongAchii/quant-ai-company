"""Read installed bytes, preserved historical records, and reporting state without new effects."""
import hashlib
import json
import subprocess
import sys
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(sys.argv[1]).resolve()
QUALIFIED = json.loads((ROOT / "qualification.json").read_text())
CUTOVER = json.loads((ROOT / "cutover-v2.json").read_text())


def run(args):
    result = subprocess.run(args, capture_output=True, text=True, timeout=60)
    if result.returncode:
        raise RuntimeError("Postcheck command failed: " + args[0])
    return result.stdout.strip()


def sql(query):
    return json.loads(run(["docker", "exec", "-u", "postgres", "quant-company-postgres-1",
        "psql", "-XqAt", "-v", "ON_ERROR_STOP=1", "-d", "quant_company", "-c",
        "BEGIN READ ONLY; " + query + "; COMMIT;"]))


def unchanged(table, originals):
    ids = ",".join("'" + i + "'" for i in originals)
    assert all(set(i) <= set("abcdefghijklmnopqrstuvwxyz0123456789-_") for i in originals)
    rows = sql("SELECT COALESCE(jsonb_agg(to_jsonb(s)),'[]'::jsonb) FROM " + table + " s WHERE id IN (" + ids + ")")
    actual = {str(row["id"]): hashlib.sha256(json.dumps(row, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
              for row in rows}
    assert actual == originals


